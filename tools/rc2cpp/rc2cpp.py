#!/usr/bin/env python3
"""Generates a C++ string table from the STRINGTABLE blocks of a Windows .rc file.

The generated source registers the strings with the RTL shim
(rtl::RegisterResourceStrings) during static initialization, so LoadStr(Ident)
finds them, see docs/port/PLAN.md section 3.3. String identifiers stay the
macros of the header the .rc file includes (TextsCore.h, ...).

Usage: rc2cpp.py INPUT.rc OUTPUT.cpp
"""

import argparse
import re
import sys
from pathlib import Path

_TOKEN_RE = re.compile(r'''
    (?P<ws>\s+)
  | (?P<comment>//[^\n]*|/\*.*?\*/)
  | (?P<string>L?"(?:[^"\\\n]|\\.|"")*")
  | (?P<ident>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<number>[0-9]+)
  | (?P<punct>,)
''', re.S | re.X)

_ESCAPES = {'n': '\n', 't': '\t', 'r': '\r', 'a': '\a', '0': '\0', '\\': '\\', '"': '"', "'": "'"}


class RcError(Exception):
    pass


def _unescape(literal):
    body = literal[literal.index('"') + 1:-1]
    result = []
    i = 0
    while i < len(body):
        char = body[i]
        if char == '\\':
            escape = body[i + 1]
            if escape not in _ESCAPES:
                raise RcError('unsupported escape \\%s' % escape)
            result.append(_ESCAPES[escape])
            i += 2
        elif char == '"':
            # "" is a quote in .rc strings
            result.append('"')
            i += 2
        else:
            result.append(char)
            i += 1
    return ''.join(result)


def _tokens(text, line_offset):
    pos = 0
    while pos < len(text):
        match = _TOKEN_RE.match(text, pos)
        if not match:
            line = line_offset + text.count('\n', 0, pos)
            raise RcError('line %d: unexpected %r' % (line, text[pos:pos + 20]))
        if match.lastgroup not in ('ws', 'comment'):
            yield match.lastgroup, match.group(0), line_offset + text.count('\n', 0, pos)
        pos = match.end()


def parse(text):
    """[(identifier, string)] of all STRINGTABLE blocks, in order."""
    entries = []
    lines = text.splitlines(keepends=True)
    index = 0
    while index < len(lines):
        if lines[index].strip() != 'STRINGTABLE':
            index += 1
            continue
        index += 1
        while index < len(lines) and lines[index].strip() != 'BEGIN':
            index += 1
        start = index + 1
        end = start
        while end < len(lines) and lines[end].strip() != 'END':
            end += 1
        if end >= len(lines):
            raise RcError('line %d: STRINGTABLE without END' % start)
        identifier = None
        strings = []
        for kind, value, line in _tokens(''.join(lines[start:end]), start + 1):
            if kind in ('ident', 'number'):
                if identifier is not None:
                    if not strings:
                        raise RcError('line %d: %s without a string' % (line, identifier))
                    entries.append((identifier, ''.join(strings)))
                identifier = value
                strings = []
            elif kind == 'string':
                if identifier is None:
                    raise RcError('line %d: string without an identifier' % line)
                strings.append(_unescape(value))
            elif strings:
                raise RcError('line %d: unexpected %r' % (line, value))
        if identifier is not None:
            if not strings:
                raise RcError('%s without a string' % identifier)
            entries.append((identifier, ''.join(strings)))
        index = end + 1
    return entries


def cpp_literal(text):
    """A wide string literal with ASCII-only source (\\u escapes)."""
    parts = []
    for char in text:
        code = ord(char)
        if char == '\\':
            parts.append('\\\\')
        elif char == '"':
            parts.append('\\"')
        elif char == '\n':
            parts.append('\\n')
        elif char == '\t':
            parts.append('\\t')
        elif char == '\r':
            parts.append('\\r')
        elif code < 0x20 or code == 0x7f:
            parts.append('\\x%02x""' % code)
        elif code < 0x80:
            parts.append(char)
        elif code < 0x10000:
            parts.append('\\u%04x' % code)
        else:
            parts.append('\\U%08x' % code)
    return 'L"%s"' % ''.join(parts)


def generate(rc_path, text):
    includes = re.findall(r'^\s*#\s*include\s*["<]([^">]+)[">]', text, re.M)
    entries = parse(text)
    out = []
    out.append('// Generated by tools/rc2cpp/rc2cpp.py from %s; do not edit.' % Path(rc_path).name)
    out.append('#include <System.hpp>')
    out += ['#include "%s"' % include for include in includes]
    out.append('')
    out.append('namespace')
    out.append('{')
    out.append('const ::rtl::TResourceString Strings[] =')
    out.append('{')
    out += ['  { %s, %s },' % (identifier, cpp_literal(string)) for identifier, string in entries]
    out.append('};')
    out.append('')
    out.append('struct TRegistration')
    out.append('{')
    out.append('  TRegistration()')
    out.append('  {')
    out.append('    ::rtl::RegisterResourceStrings(Strings, sizeof(Strings) / sizeof(Strings[0]));')
    out.append('  }')
    out.append('};')
    out.append('')
    out.append('// After the RTL (150, 200), before the static objects of the code using the strings')
    out.append('TRegistration Registration __attribute__((init_priority(300)));')
    out.append('}')
    return '\n'.join(out) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('input', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args(argv)
    try:
        result = generate(args.input, args.input.read_bytes().decode('utf-8-sig'))
    except RcError as error:
        print('%s: %s' % (args.input, error), file=sys.stderr)
        return 1
    if not args.output.exists() or args.output.read_text() != result:
        args.output.write_text(result)
    return 0


if __name__ == '__main__':
    sys.exit(main())
