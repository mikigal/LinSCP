#!/bin/bash
# Provisions the LinSCP test VM (Debian 13): the servers and users of the
# L2 tests, see docs/port/PLAN.md section 6.3. Idempotent; runs as root on
# the VM, with testvm.env and client_ed25519.pub next to it. Run it from the
# client with: tools/testenv/testvm.py provision
set -euo pipefail

cd "$(dirname "$0")"
# shellcheck source=testvm.env
. ./testvm.env

export DEBIAN_FRONTEND=noninteractive

CONFIG_DIR=/etc/ssh/linscp
CHROOT_DIR=/srv/linscp/chroot
TLS_DIR=/etc/linscp/tls
PROFTPD_DIR=/opt/linscp/proftpd
PUREFTPD_DIR=/opt/linscp/pure-ftpd

install_packages()
{
  local missing=()
  local package
  for package in "$@"; do
    if ! dpkg-query -W -f='${Status}' "$package" 2>/dev/null | grep -q "ok installed"; then
      missing+=("$package")
    fi
  done
  if [ ${#missing[@]} -gt 0 ]; then
    apt-get update -q
    apt-get install -q -y --no-install-recommends "${missing[@]}"
  fi
}

# The servers of the tests were named after OpenSCP before the project was
# renamed to LinSCP (2026-10-25): their services and sites go; their host
# keys, TLS certificate, S3 credentials and data move to the new names
remove_former_names()
{
  local name
  for name in openscp-sshd openscp-vsftpd openscp-vsftpd-implicit openscp-proftpd openscp-pureftpd openscp-s3; do
    if [ -f "/etc/systemd/system/$name.service" ]; then
      systemctl disable -q --now "$name.service" || true
      rm -f "/etc/systemd/system/$name.service"
    fi
  done
  systemctl daemon-reload
  if [ -f /etc/apache2/sites-available/openscp-dav.conf ]; then
    a2dissite -q openscp-dav >/dev/null || true
    rm -f /etc/apache2/sites-available/openscp-dav.conf
  fi
  rm -f /etc/nginx/sites-enabled/openscp /etc/nginx/sites-available/openscp
  local from
  for from in /etc/ssh/openscp /etc/openscp /srv/openscp; do
    if [ -d "$from" ] && [ ! -e "${from/openscp/linscp}" ]; then
      mv "$from" "${from/openscp/linscp}"
    fi
  done
  rm -rf /opt/openscp /usr/local/lib/openscp /usr/local/bin/openscp-s3 /var/log/openscp
}

# A user with the test password (reset on every run, as the tests change it)
ensure_user()
{
  local name=$1
  if ! id -u "$name" >/dev/null 2>&1; then
    useradd --create-home --shell /bin/bash "$name"
  fi
  echo "$name:$SSH_PASSWORD" | chpasswd
  chage -d "$(date +%Y-%m-%d)" -M 99999 "$name"
}

authorize_client_key()
{
  local name=$1
  local home
  home=$(getent passwd "$name" | cut -d: -f6)
  install -d -m 700 -o "$name" -g "$name" "$home/.ssh"
  install -m 600 -o "$name" -g "$name" client_ed25519.pub "$home/.ssh/authorized_keys"
}

provision_ssh()
{
  install_packages openssh-server openssh-sftp-server openssh-client

  ensure_user "$SSH_PASSWORD_USER"
  ensure_user "$SSH_KBD_USER"
  ensure_user "$SSH_EXPIRED_USER"
  chage -d 0 "$SSH_EXPIRED_USER"
  ensure_user "$SSH_TWOFACTOR_USER"
  authorize_client_key "$SSH_TWOFACTOR_USER"
  ensure_user "$SSH_CHROOT_USER"
  ensure_user "$SSH_COPYID_USER"
  rm -f "$(getent passwd "$SSH_COPYID_USER" | cut -d: -f6)/.ssh/authorized_keys"

  # The chroot must be owned by root and not writable by others
  install -d -m 755 -o root -g root /srv/linscp "$CHROOT_DIR"
  install -d -m 755 -o "$SSH_CHROOT_USER" -g "$SSH_CHROOT_USER" "$CHROOT_DIR/upload"

  install -d -m 755 "$CONFIG_DIR"
  local type
  for type in ed25519 ecdsa rsa; do
    if [ ! -f "$CONFIG_DIR/ssh_host_${type}_key" ]; then
      ssh-keygen -q -t "$type" -N "" -C "linscp-test-vm" -f "$CONFIG_DIR/ssh_host_${type}_key"
    fi
  done

  cat > "$CONFIG_DIR/sshd_config" <<EOF
# The OpenSSH server of the LinSCP tests (generated by provision.sh)
Port $SSH_PORT
HostKey $CONFIG_DIR/ssh_host_ed25519_key
HostKey $CONFIG_DIR/ssh_host_ecdsa_key
HostKey $CONFIG_DIR/ssh_host_rsa_key
PidFile /run/linscp-sshd.pid
UsePAM yes
PermitRootLogin no
PubkeyAuthentication yes
PasswordAuthentication yes
KbdInteractiveAuthentication yes
MaxAuthTries 20
# The tests fail authentication on purpose
PerSourcePenalties no
Banner $CONFIG_DIR/banner
Subsystem sftp internal-sftp
AcceptEnv LANG LC_*

Match User $SSH_PASSWORD_USER
  AuthenticationMethods password
Match User $SSH_KBD_USER,$SSH_EXPIRED_USER
  AuthenticationMethods keyboard-interactive
Match User $SSH_TWOFACTOR_USER
  AuthenticationMethods publickey,password
Match User $SSH_CHROOT_USER
  AuthenticationMethods password
  ChrootDirectory $CHROOT_DIR
  ForceCommand internal-sftp
EOF
  echo "LinSCP test server" > "$CONFIG_DIR/banner"
  sshd -t -f "$CONFIG_DIR/sshd_config"

  cat > /etc/systemd/system/linscp-sshd.service <<EOF
[Unit]
Description=OpenSSH server of the LinSCP tests
After=network.target

[Service]
ExecStartPre=/usr/bin/mkdir -p /run/sshd
ExecStartPre=/usr/sbin/sshd -t -f $CONFIG_DIR/sshd_config
ExecStart=/usr/sbin/sshd -D -f $CONFIG_DIR/sshd_config
ExecReload=/bin/kill -HUP \$MAINPID
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable -q linscp-sshd.service
  systemctl restart linscp-sshd.service
}

# A self-signed certificate of the TLS servers (FTPS, WebDAV, S3), kept
# across runs, so that its fingerprint stays
provision_tls()
{
  install_packages openssl
  install -d -m 755 "$TLS_DIR"
  if [ ! -f "$TLS_DIR/cert.pem" ] || [ ! -f "$TLS_DIR/key.pem" ]; then
    openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
      -subj "/O=LinSCP tests/CN=linscp-test-vm" \
      -keyout "$TLS_DIR/key.pem" -out "$TLS_DIR/cert.pem" 2>/dev/null
  fi
  chmod 644 "$TLS_DIR/cert.pem"
  chmod 600 "$TLS_DIR/key.pem"
}

# A systemd service of the tests: name, description, command, extra lines
# of the [Service] section
install_service()
{
  local name=$1 description=$2 command=$3 extra=${4:-}
  cat > "/etc/systemd/system/$name.service" <<EOF
[Unit]
Description=$description
After=network.target

[Service]
ExecStart=$command
Restart=on-failure
$extra

[Install]
WantedBy=multi-user.target
EOF
}

restart_services()
{
  systemctl daemon-reload
  local name
  for name in "$@"; do
    systemctl enable -q "$name.service"
    systemctl restart "$name.service"
  done
}

# Services of packages whose servers run with the configurations of the
# tests instead
disable_package_services()
{
  local name
  for name in "$@"; do
    systemctl disable -q --now "$name.service" 2>/dev/null || true
  done
}

# vsftpd configuration: port, first passive port, implicit TLS (YES/NO)
vsftpd_config()
{
  local port=$1 passive=$2 implicit=$3 name=$4
  cat <<EOF
# vsftpd of the LinSCP tests (generated by provision.sh)
listen=YES
listen_ipv6=NO
listen_port=$port
background=NO
anonymous_enable=NO
local_enable=YES
write_enable=YES
local_umask=022
chmod_enable=YES
dirmessage_enable=NO
use_localtime=NO
xferlog_enable=NO
connect_from_port_20=NO
pasv_enable=YES
pasv_min_port=$passive
pasv_max_port=$((passive + 99))
secure_chroot_dir=/run/$name
pam_service_name=vsftpd
seccomp_sandbox=NO
ssl_enable=YES
implicit_ssl=$implicit
rsa_cert_file=$TLS_DIR/cert.pem
rsa_private_key_file=$TLS_DIR/key.pem
allow_anon_ssl=NO
force_local_data_ssl=NO
force_local_logins_ssl=NO
require_ssl_reuse=YES
utf8_filesystem=YES
ascii_upload_enable=YES
ascii_download_enable=YES
EOF
}

# Unpacks packages to a directory instead of installing them (the FTP
# servers of Debian conflict with each other); their libraries must be
# installed
unpack_packages()
{
  local target=$1
  shift
  local dir deb
  dir=$(mktemp -d)
  chown _apt "$dir"
  (cd "$dir" && apt-get download -q "$@" >/dev/null)
  rm -rf "$target"
  install -d -m 755 "$target"
  for deb in "$dir"/*.deb; do
    dpkg-deb -x "$deb" "$target"
  done
  rm -rf "$dir"
}

provision_ftp()
{
  install_packages vsftpd \
    libacl1 libcap2 libcrypt1 libhiredis1.1.0 libidn2-0 libmemcached11t64 libmemcachedutil2t64 \
    libncursesw6 libpam0g libpcre2-8-0 libpcre2-posix3 libsodium23 libssl3t64 libtinfo6 zlib1g
  # The unpacked servers are built against the current libraries
  apt-get install -q -y --only-upgrade libssl3t64 libsodium23 >/dev/null
  disable_package_services vsftpd
  unpack_packages "$PROFTPD_DIR" proftpd-core proftpd-mod-crypto
  unpack_packages "$PUREFTPD_DIR" pure-ftpd

  local passive=$FTP_PASSIVE_PORTS_START
  vsftpd_config "$VSFTPD_PORT" "$passive" NO linscp-vsftpd > /etc/linscp/vsftpd.conf
  vsftpd_config "$VSFTPD_IMPLICIT_PORT" "$((passive + 100))" YES linscp-vsftpd-implicit \
    > /etc/linscp/vsftpd-implicit.conf
  install_service linscp-vsftpd "vsftpd of the LinSCP tests" \
    "/usr/sbin/vsftpd /etc/linscp/vsftpd.conf" "RuntimeDirectory=linscp-vsftpd"
  install_service linscp-vsftpd-implicit "vsftpd with implicit TLS of the LinSCP tests" \
    "/usr/sbin/vsftpd /etc/linscp/vsftpd-implicit.conf" "RuntimeDirectory=linscp-vsftpd-implicit"

  install -d -m 755 /var/log/linscp
  cat > /etc/linscp/proftpd.conf <<EOF
# ProFTPD of the LinSCP tests (generated by provision.sh)
ModulePath $PROFTPD_DIR/usr/lib/proftpd
LoadModule mod_xfer.c
LoadModule mod_ls.c
LoadModule mod_tls.c
ServerName "LinSCP test ProFTPD"
ServerType standalone
DefaultServer on
Port $PROFTPD_PORT
UseIPv6 off
User nobody
Group nogroup
Umask 022
MaxInstances 30
PassivePorts $((passive + 200)) $((passive + 299))
AllowOverwrite on
AllowStoreRestart on
UseReverseDNS off
RequireValidShell on
PidFile /run/linscp-proftpd.pid
ScoreboardFile /run/linscp-proftpd.scoreboard
WtmpLog off
TransferLog none
SystemLog /var/log/linscp/proftpd.log
AuthOrder mod_auth_unix.c
<IfModule mod_tls.c>
  TLSEngine on
  TLSLog /var/log/linscp/proftpd-tls.log
  TLSProtocol TLSv1.2 TLSv1.3
  TLSRSACertificateFile $TLS_DIR/cert.pem
  TLSRSACertificateKeyFile $TLS_DIR/key.pem
  TLSRequired off
  TLSVerifyClient off
</IfModule>
EOF
  local output
  if ! output=$("$PROFTPD_DIR/usr/sbin/proftpd" --configtest -c /etc/linscp/proftpd.conf 2>&1); then
    echo "$output" >&2
    return 1
  fi
  install_service linscp-proftpd "ProFTPD of the LinSCP tests" \
    "$PROFTPD_DIR/usr/sbin/proftpd --nodaemon -c /etc/linscp/proftpd.conf"

  install_service linscp-pureftpd "Pure-FTPd of the LinSCP tests" \
    "$PUREFTPD_DIR/usr/sbin/pure-ftpd -S 0.0.0.0,$PUREFTPD_PORT -p $((passive + 300)):$((passive + 399)) -l unix -E -H -Y 1 -2 $TLS_DIR/cert.pem,$TLS_DIR/key.pem"

  restart_services linscp-vsftpd linscp-vsftpd-implicit linscp-proftpd linscp-pureftpd
}

provision_webdav()
{
  install_packages apache2 apache2-utils nginx libnginx-mod-http-dav-ext
  install -d -m 755 /srv/linscp/dav
  install -d -m 755 -o www-data -g www-data /srv/linscp/dav/apache /srv/linscp/dav/nginx
  htpasswd -b -c -m /etc/linscp/dav.htpasswd "$SSH_PASSWORD_USER" "$SSH_PASSWORD" 2>/dev/null
  chgrp www-data /etc/linscp/dav.htpasswd
  chmod 640 /etc/linscp/dav.htpasswd

  # Apache: only the ports of the tests
  a2dissite -q 000-default >/dev/null
  a2enmod -q dav dav_fs ssl auth_basic authn_file >/dev/null
  cat > /etc/apache2/ports.conf <<EOF
# Generated by the LinSCP provision.sh
Listen $APACHE_DAV_PORT
Listen $APACHE_DAVS_PORT
EOF
  cat > /etc/apache2/sites-available/linscp-dav.conf <<EOF
# WebDAV of the LinSCP tests (generated by provision.sh)
<Directory /srv/linscp/dav/apache>
  Dav On
  AuthType Basic
  AuthName "LinSCP tests"
  AuthUserFile /etc/linscp/dav.htpasswd
  Require valid-user
  Options +Indexes
  AllowOverride None
</Directory>
<VirtualHost *:$APACHE_DAV_PORT>
  DocumentRoot /srv/linscp/dav/apache
</VirtualHost>
<VirtualHost *:$APACHE_DAVS_PORT>
  DocumentRoot /srv/linscp/dav/apache
  SSLEngine on
  SSLCertificateFile $TLS_DIR/cert.pem
  SSLCertificateKeyFile $TLS_DIR/key.pem
</VirtualHost>
EOF
  a2ensite -q linscp-dav >/dev/null
  local output
  if ! output=$(apache2ctl configtest 2>&1); then
    echo "$output" >&2
    return 1
  fi

  rm -f /etc/nginx/sites-enabled/default
  cat > /etc/nginx/sites-available/linscp <<EOF
# WebDAV and the TLS proxy of S3 of the LinSCP tests (generated by
# provision.sh)
server {
  listen $NGINX_DAV_PORT;
  listen $NGINX_DAVS_PORT ssl;
  ssl_certificate $TLS_DIR/cert.pem;
  ssl_certificate_key $TLS_DIR/key.pem;
  root /srv/linscp/dav/nginx;
  client_max_body_size 0;
  location / {
    auth_basic "LinSCP tests";
    auth_basic_user_file /etc/linscp/dav.htpasswd;
    dav_methods PUT DELETE MKCOL COPY MOVE;
    dav_ext_methods PROPFIND OPTIONS;
    dav_access user:rw group:rw all:r;
    create_full_put_path on;
    autoindex on;
  }
}
server {
  listen $S3S_PORT ssl;
  ssl_certificate $TLS_DIR/cert.pem;
  ssl_certificate_key $TLS_DIR/key.pem;
  client_max_body_size 0;
  location / {
    # (The host is signed)
    proxy_set_header Host \$http_host;
    proxy_pass http://127.0.0.1:$S3_PORT;
    proxy_http_version 1.1;
    proxy_request_buffering off;
    proxy_buffering off;
  }
}
EOF
  ln -sf /etc/nginx/sites-available/linscp /etc/nginx/sites-enabled/linscp
  nginx -t -q

  systemctl enable -q apache2.service nginx.service
  systemctl restart apache2.service nginx.service
}

provision_s3()
{
  install_packages python3-moto python3-flask python3-flask-cors python3-boto3
  install -d -m 755 /usr/local/lib/linscp
  install -m 755 s3-server.py s3-bootstrap.py /usr/local/lib/linscp/
  sed "s/^PORT = .*/PORT = $S3_PORT/" linscp-s3 > /usr/local/bin/linscp-s3
  chmod 755 /usr/local/bin/linscp-s3
  install_service linscp-s3 "S3 server (moto) of the LinSCP tests" \
    "/usr/local/lib/linscp/s3-server.py -H 0.0.0.0 -p $S3_PORT" \
    "User=nobody
ExecStartPost=+/usr/local/lib/linscp/s3-bootstrap.py $S3_PORT /etc/linscp/s3-credentials
UMask=0077"
  restart_services linscp-s3
}

remove_former_names
install -d -m 755 /etc/linscp
provision_ssh
provision_tls
provision_ftp
provision_webdav
provision_s3
echo "provisioned"
