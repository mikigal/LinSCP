// Fixed-size array as generated by C++Builder for Delphi static arrays
template <class T, size_t N>
class StaticArray
{
public:
  T & operator [](size_t Index) { return FData[Index]; }
  const T & operator [](size_t Index) const { return FData[Index]; }
  operator T * () { return FData; }
  operator const T * () const { return FData; }
  static constexpr size_t Size() { return N; }
  T * begin() { return FData; }
  T * end() { return FData + N; }
  const T * begin() const { return FData; }
  const T * end() const { return FData + N; }

  T FData[N];
};
